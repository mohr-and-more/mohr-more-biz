/**
 * Generates `public/_headers` from the shared Context7 Ask endpoint.
 *
 * Cloudflare Pages reads `_headers` from the deployed directory, and Next
 * copies `public/` into `out/`, so the `Link` header ships with every page
 * response. The endpoint is read from `src/lib/context7-ask.json` — the same
 * file the app imports — so it is never repeated here.
 *
 * Runs automatically before `next dev` and `next build` (npm `predev` /
 * `prebuild`).
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const { baseUrl, siteKey } = JSON.parse(
  readFileSync(join(root, "src/lib/context7-ask.json"), "utf8"),
);
const endpoint = `${baseUrl}?siteKey=${siteKey}`;

const headers = `# Generated by scripts/context7-ask-headers.mjs — do not edit by hand.
# Context7 Ask search endpoint (see src/lib/context7-ask.json).

/*
  Link: <${endpoint}>; rel="search"; type="text/plain"; title="Search mohr-more.biz"
`;

writeFileSync(join(root, "public/_headers"), headers);
console.log("context7-ask: wrote public/_headers");
